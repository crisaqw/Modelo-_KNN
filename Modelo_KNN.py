# Só execute esta celula se preferir adcionar o arquivo da planilha manualmente
dados = pd.read_csv('plan. de dados mod.csv', sep=',')

# Faz a leitura da planilha de dados diretamente online do meu repositório, sem necessidade de fazer upload
dados = pd.read_csv('https://raw.githubusercontent.com/crisaqw/Nova-planilha-de-dados/refs/heads/main/planilha%20teste%20novas%20configs(3)%20sem%20o%20grupo%201.csv', sep=',')

"""3. Separar entrada (IA) e saída (classe)"""

X = dados [['Altura (m)', 'Ângulo (º)', 'Tempo (s)']]
y = dados ['Objeto']

"""4. Separar treino e teste"""

X_treino, X_teste, y_treino, y_teste = train_test_split(
    X, y, test_size=0.3, random_state=0, stratify=y
)
#📌 A IA aprende com parte dos dados e é testada com dados “novos”.

"""5. Escalonar os dados (passo técnico obrigatório)"""

scaler = MinMaxScaler()
X_treino = scaler.fit_transform(X_treino)
X_teste = scaler.transform(X_teste)

#👉 Sem isso, o KNN não funciona direito.

"""6. Treinar a IA (KNN)"""

knn = KNeighborsClassifier(n_neighbors=5)
knn.fit(X_treino, y_treino)
#📌 Aqui a IA aprende a classificar.

"""🔹 7. Avaliar a classificação"""

y_pred = knn.predict(X_teste)

print("Acurácia:", accuracy_score(y_teste, y_pred))

"""🔹 8. Visualizar a classificação da IA"""

classes = ['esfera', 'cilindro', 'aro']

matriz = confusion_matrix(
    y_teste,
    y_pred,
    labels=classes
)
sns.heatmap(
    matriz,
    annot=True,
    fmt='d',
    cmap='YlGn',
    xticklabels=classes,
    yticklabels=classes
)
plt.xlabel('Predito pela IA')
plt.ylabel('Objeto real')
plt.title('Classificação por IA (KNN)')
plt.show();
#A IA erra quando os padrões se sobrepõem.

"""⚙️ MODELO FÍSICO (EXPLICAÇÃO)

🔹 9. Função física para calcular β
"""

def calcula_beta(altura, tempo, angulo):
    g = 9.8
    distancia = altura / np.sin(np.deg2rad(angulo))
    vmed = distancia / tempo
    beta = (0.5 * g * altura) / (vmed**2) - 1
    return beta

"""10. Aplicar o modelo físico aos dados"""

dados['Beta (Fisica)'] = dados.apply(
    lambda x: calcula_beta(x['Altura (m)'], x['Tempo (s)'], x['Ângulo (º)']),
    axis=1
)

"""11. Visualizar a explicação física"""

plt.figure(figsize=(6,4))

sns.stripplot(
    data=dados,
    x='Beta (Fisica)',
    y='Objeto',
    order=['esfera', 'cilindro', 'aro'],
    jitter=True,
    palette='YlGn'
)

plt.xlabel('β (Modelo Físico)')
plt.ylabel('')
plt.title('Modelo Físico: parâmetro β por objeto')

plt.xlim(-0.5, 2)
